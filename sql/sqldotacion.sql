DROP VIEW IF EXISTS vw_dotacion_consolidada;
CREATE VIEW vw_dotacion_consolidada AS
SELECT
    d.rut,
    d.nombre_completo,
    d.usuario_login,
    d.supervisor_asignado,
    d.estado_dotacion,
    d.contrato_desde,
    d.contrato_hasta,
    d.tipo_contrato,
    d.jornada,
    d.modalidad,
    d.call_center,
    d.servicio,
    d.jefatura,
    d.hoja_origen,
    d.fecha_importacion,
    d.fecha_actualizacion
FROM tbl_dotacion d;
