CREATE DATABASE IF NOT EXISTS gestion_operativa CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE gestion_operativa;

CREATE TABLE IF NOT EXISTS tbl_dotacion (
    id_dotacion INT AUTO_INCREMENT PRIMARY KEY,
    rut VARCHAR(20) NOT NULL,
    nombre_completo VARCHAR(255) NOT NULL,
    usuario_login VARCHAR(100) DEFAULT NULL,
    supervisor_asignado VARCHAR(255) DEFAULT NULL,
    estado_dotacion VARCHAR(60) NOT NULL DEFAULT 'Activo',
    contrato_desde DATETIME DEFAULT NULL,
    contrato_hasta DATETIME DEFAULT NULL,
    tipo_contrato VARCHAR(120) DEFAULT NULL,
    jornada VARCHAR(50) DEFAULT NULL,
    modalidad VARCHAR(120) DEFAULT NULL,
    call_center VARCHAR(120) DEFAULT NULL,
    servicio VARCHAR(255) DEFAULT NULL,
    jefatura VARCHAR(255) DEFAULT NULL,
    hoja_origen VARCHAR(100) DEFAULT NULL,
    fecha_importacion DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_actualizacion DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    UNIQUE KEY uq_tbl_dotacion_rut (rut),
    KEY idx_tbl_dotacion_estado (estado_dotacion),
    KEY idx_tbl_dotacion_supervisor (supervisor_asignado),
    KEY idx_tbl_dotacion_usuario (usuario_login),
    KEY idx_tbl_dotacion_jefatura (jefatura)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

